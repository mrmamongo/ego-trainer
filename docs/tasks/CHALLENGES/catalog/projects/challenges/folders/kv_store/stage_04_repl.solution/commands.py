"""Команды хранилища: разбор строки."""


def parse_command(line):
    """Разобрать строку команды: вернуть пару (ИМЯ, [аргументы]).

    Имя — заглавными буквами, лишние пробелы по краям не считаются.
    Пример: "set a 1" -> ("SET", ["a", "1"])
    Пустая строка -> ("", [])
    """
    words = line.split()
    if len(words) == 0:
        return ("", [])
    return (words[0].upper(), words[1:])
