"""XL-O-04 — Исправь расчёт вероятностей для sampling.

В старом коде реализован softmax, но на больших logits он переполняется, а
запрещённые токены ломают нормализацию. Твоя задача — аккуратно исправить
probabilities(logits, temperature=1.0), не меняя её публичный интерфейс.

Положительный temperature делит каждый разрешённый logit перед softmax.
Сначала найди максимум уже масштабированных значений и вычти его перед exp —
так расчёт устойчив к большим числам. Значение float('-inf') означает
запрещённый токен и всегда должно получить вероятность 0.

При temperature == 0 используй greedy-режим: ровно один максимальный
разрешённый logit получает 1.0, остальные 0.0. При одинаковых максимумах
выбирай токен с меньшим индексом. Если все logits запрещены, верни список
нулей. Для обычного случая сумма вероятностей должна быть близка к 1.

Не допускай деления на ноль и не изменяй исходный список. Подумай о пустом
списке, одном токене и очень больших значениях вроде 10000 и 10001.
"""

import math


def probabilities(logits, temperature=1.0):
    # Намеренная неисправная реализация.
    scaled = [value / temperature for value in logits]
    values = [math.exp(value) for value in scaled]
    total = sum(values)
    return [value / total for value in values]
