"""XL-O-07 — Исправь сборку потокового ответа после реконнекта.

Streaming API присылает события data и done. У data есть chunk_id, sequence и
text. При временном разрыве соединения сервер может прислать уже доставленный
chunk повторно. Исправь collect_chunks(events), чтобы пользователь не увидел
дубликаты и перемешанный текст.

Сохрани только первое событие каждого chunk_id, затем упорядочь уникальные
чанки по sequence и склей text. После первого done обработку можно завершить;
повторный done не должен влиять на результат. Если done отсутствует, собери
все data, которые пришли. Не теряй chunk из-за того, что done встретился после
него, и не мутируй events.

Проверь события в порядке 2, 1, 2, done, а также пустой поток, повторный
chunk с другим text и поток без done. Результат функции — строка ответа.
"""


def collect_chunks(events):
    # Намеренная ошибка: список допускает дубли и порядок доставки используется
    return "".join(event["text"] for event in events if event["kind"] == "data")
