"""Задача I4: BPE tokenize — найди баг

Блок: XL-K — LLM-токенайзер
Сложность: bug
Тип: найди баг
Темы: BPE, токенизация, граничные случаи, отладка

== УСЛОВИЕ ==

Ниже функция tokenize_bpe применяет словарь слияний BPE к списку
токенов: если в словаре есть пара соседних токенов, она заменяется
одним новым токеном, пока ни одна пара не совпадает.

НО в коде есть баги:
  1) при обработке пустого списка падает с IndexError
  2) последний токен теряется из результата
  3) пара, которой нет в merges, не должна трогаться, но код
     «сливает» и её, подставляя второй элемент первого

== АРГУМЕНТЫ ==

- tokens — список строк: ["t", "h", "e", " ", "c", "a", "t"]
- merges — dict: пара (tuple из двух строк) -> строка (результат слияния)

== ВОЗВРАЩАЕТ ==

Список строк — токены после применения всех возможных слияний.

== ПРАВИЛА ==

- Слияние применяется слева направо, одна пара за проход.
- Если ни одна пара не найдена — возвращаем исходный список.
- Пустой список → пустой список.

== ПРИМЕР ==

  tokens = ["t", "h", "e", " ", "c", "a", "t"]
  merges = {("t", "h"): "th", ("th", "e"): "the", ("c", "a"): "ca"}
  # -> ["the", " ", "ca", "t"]  (пара ("a", "t") не в merges, остаётся как есть)

НАЙДИ И ИСПРАВЬ БАГИ. Не переписывай функцию с нуля — только исправления.
"""


def task_xli4_tokenize_bpe(tokens, merges):
    """Применяет BPE-слияния к списку токенов."""
    if len(tokens) == 0:
        return []

    result = []
    i = 0
    while i < len(tokens) - 1:
        pair = (tokens[i], tokens[i + 1])
        result.append(merges.get(pair, tokens[i + 1]))

        if pair in merges:
            i += 1  # пропускаем оба элемента пары

        i += 1
    # обрабатываем последнюю пару
    last_pair = (tokens[-2], tokens[-1])
    result.append(merges.get(last_pair, tokens[-1]))
    return result
