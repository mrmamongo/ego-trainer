"""Задача I6: Триминг контекста — найди баг

Блок: XL-K — LLM-токенайзер
Сложность: bug
Тип: найди баг
Темы: контекстное окно, обрезка строк, отладка

== УСЛОВИЕ ==

Ниже функция trim_context обрезает историю сообщений, чтобы суммарная
длина content (в символах) не превышала limit. Она должна выкидывать
самые СТАРЫЕ сообщения (с начала списка), пока суммарная длина
content остальных сообщений не станет <= limit.

Баги:
    1) выдаются всегда все сообщения
    2) если оно и работает, то выдаётся на одно сообщение больше, чем нужно
    3) на длинах контекста больше 10000 цикл начинает работать очень долго

== АРГУМЕНТЫ ==

- messages — список dict: [{"role": "user"|"assistant", "content": str}, ...]
- limit — целое, максимальная суммарная длина content

== ВОЗВРАЩАЕТ ==

Список сообщений (подсписок исходного, с конца), где
sum(len(m["content"])) <= limit.

== ПРАВИЛА ==

- Убираем сообщения с НАЧАЛА списка.
- Если даже одно сообщение длиннее limit — оно тоже убирается.
- Пустой список → пустой список.

== ПРИМЕР ==

  messages = [
      {"role": "user", "content": "aaa"},
      {"role": "assistant", "content": "bb"},
      {"role": "user", "content": "c"},
  ]
  trim_context(messages, 3)
  # -> [{"role": "user", "content": "c"}]  (сумма 3 <= 3)

НАЙДИ И ИСПРАВЬ БАГИ. Не переписывай функцию с нуля — только исправления.
"""


def trim_context(messages, limit):
    """Обрезает историю сообщений до лимита суммарной длины content."""
    msgs = list(messages)
    if limit > 0:
        while msgs and sum(len(m.get("text", "")) for m in msgs) > limit:
            msgs.pop(0)
    return msgs


def task_xli6_trim_context(messages, limit):
    # Вызови исправленный trim_context, исправив баги выше
    return trim_context(messages, limit)
